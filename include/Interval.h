#pragma once
#include "Trial.h"

/**
 * @brief Класс, представляющий интервал между двумя точками
 * 
 * Интервал содержит левую и правую точки, а также характеристику R,
 * которая используется для выбора интервала на следующей итерации
 */
class Interval
{
public:
  /// Левая точка интервала
  Trial* left;
  
  /// Правая точка интервала
  Trial* right;
  
  /// Характеристика интервала
  double R;
  
  /// Порядковый номер создания
  int numberCreate;

  /**
   * @brief Конструктор по умолчанию
   */
  Interval();
  
  /**
   * @brief Деструктор
   */
  ~Interval();

  /**
   * @brief Оператор сравнения для очереди с приоритетом
   * @param a Первый интервал
   * @param b Второй интервал
   * @return true если характеристика a меньше b
   */
  bool operator () (const Interval* a, const Interval* b);
};
