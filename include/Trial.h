#pragma once

#include <vector>

/**
 * @brief Класс, представляющий испытание (точку поиска)
 * 
 * Содержит одномерную координату x (после развертки) и многомерные
 * координаты y (в исходном пространстве), а также значения функций z
 */
class Trial
{
protected:
  static int TrialNumberCreate;
  
public:
  /// Одномерная координата (после развертки Пеано)
  double x;
  
  /// Координаты в многомерном пространстве
  std::vector<double> y;
  
  /// Значения функций в точке
  std::vector<double> z;
  
  /// Порядковый номер создания точки
  int numberCreate;

  /**
   * @brief Конструктор по умолчанию
   * @param _x Одномерная координата
   */
  Trial(double _x = 0);
  
  /**
   * @brief Конструктор с многомерными координатами
   * @param y Вектор многомерных координат
   */
  Trial(std::vector<double> y);
  
  /**
   * @brief Конструктор копирования
   * @param p Копируемое испытание
   */
  Trial(const Trial& p);
};
